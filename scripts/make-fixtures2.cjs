// --- PNG real para incrustar en el gcode ---------------------------
function crc32(b) {
  let c = ~0
  for (let i = 0; i < b.length; i++) {
    c ^= b[i]
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1))
  }
  return ~c
}
function chunk(t, d) {
  const o = Buffer.alloc(12 + d.length)
  o.writeUInt32BE(d.length, 0)
  o.write(t, 4)
  d.copy(o, 8)
  o.writeUInt32BE(crc32(Buffer.concat([Buffer.from(t), d])) >>> 0, 8 + d.length)
  return o
}
function png(n) {
  const raw = Buffer.alloc((n * 3 + 1) * n)
  let p = 0
  for (let y = 0; y < n; y++) {
    raw[p++] = 0
    for (let x = 0; x < n; x++) {
      raw[p++] = 40
      raw[p++] = (x / n) * 220
      raw[p++] = (y / n) * 220
    }
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(n, 0)
  ihdr.writeUInt32BE(n, 4)
  ihdr[8] = 8
  ihdr[9] = 2
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0))
  ])
}
const b64 = png(64).toString('base64')
